#!/usr/bin/env python3
"""OpenHands adapter — Protocol v1.1 + workspace-per-run_id enforcement (M2)."""

from __future__ import annotations

import json
import os
import shutil
import time
import traceback
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import redis

JOB_QUEUE = os.getenv("OPENHANDS_JOB_QUEUE", "aicos:jobs:openhands")
RESULT_QUEUE = os.getenv("RESULT_QUEUE", "aicos:results")
HEARTBEAT_QUEUE = os.getenv("HEARTBEAT_QUEUE", "aicos:heartbeats")
EVENTS_PREFIX = os.getenv("EVENTS_CHANNEL_PREFIX", "aicos:run:")
REDIS_URL = os.getenv("REDIS_URL", "redis://localhost:6379/0")
STUB = os.getenv("OPENHANDS_STUB", "1") == "1"
WORKSPACE_ROOT = Path(os.getenv("OPENHANDS_WORKSPACE_ROOT", "/tmp/aicos-openhands")).resolve()


def client() -> redis.Redis:
    return redis.from_url(REDIS_URL, decode_responses=True)


def docker_available() -> bool:
    return shutil.which("docker") is not None


def publish(r: redis.Redis, run_id: str, event_type: str, payload: dict[str, Any] | None = None) -> dict:
    ev = {"type": event_type, "payload": payload or {}, "run_id": run_id}
    r.publish(f"{EVENTS_PREFIX}{run_id}", json.dumps(ev))
    return ev


def heartbeat(r: redis.Redis, job: dict[str, Any]) -> None:
    r.rpush(
        HEARTBEAT_QUEUE,
        json.dumps(
            {
                "run_id": job["run_id"],
                "dispatch_id": job.get("dispatch_id"),
                "at": datetime.now(UTC).isoformat(),
            }
        ),
    )


def cancelled(r: redis.Redis, run_id: str) -> bool:
    return r.get(f"aicos:run:cancel:{run_id}") == "1"


def assert_workspace(run_id: str, job: dict[str, Any]) -> Path:
    """Enforce one workspace directory strictly under WORKSPACE_ROOT / run_id."""
    required = (job.get("workspace") or {}).get("root_required")
    ws = (WORKSPACE_ROOT / run_id).resolve()
    if not str(ws).startswith(str(WORKSPACE_ROOT) + os.sep) and ws != WORKSPACE_ROOT:
        raise RuntimeError(f"Workspace escape blocked: {ws}")
    if required:
        req = Path(required).resolve()
        if req != ws:
            raise RuntimeError(f"Workspace mismatch: required={req} got={ws}")
    # Refuse writing outside run_id folder
    if ".." in run_id or "/" in run_id or "\\" in run_id:
        raise RuntimeError("Invalid run_id for workspace")
    ws.mkdir(parents=True, exist_ok=True)
    # Marker file proves isolation
    (ws / ".aicos_workspace").write_text(f"run_id={run_id}\n")
    return ws


def destroy_workspace(ws: Path) -> None:
    if ws.exists() and str(ws).startswith(str(WORKSPACE_ROOT)):
        # Keep artifact for smoke by default; destroy only if env set
        if os.getenv("OPENHANDS_DESTROY_ON_FINISH", "0") == "1":
            shutil.rmtree(ws, ignore_errors=True)


def handle_stub(job: dict[str, Any], r: redis.Redis) -> dict[str, Any]:
    run_id = job["run_id"]
    dispatch_id = job.get("dispatch_id")
    events = []
    events.append(
        publish(
            r,
            run_id,
            "run.started",
            {"adapter": "openhands", "mode": "stub", "docker": False, "dispatch_id": dispatch_id, "protocol": "1.1"},
        )
    )
    heartbeat(r, job)

    if cancelled(r, run_id):
        return _terminal(job, "cancelled", "Cancelled before sandbox start", events, [])

    ws = assert_workspace(run_id, job)
    sample = ws / "hello.py"
    # Path must remain under ws
    if not str(sample.resolve()).startswith(str(ws)):
        raise RuntimeError("File path escaped workspace")
    sample.write_text("# generated by openhands stub\nprint('hello from sandbox stub')\n")
    events.append(
        publish(
            r,
            run_id,
            "tool.result",
            {"tool": "FileEditorTool", "path": str(sample), "action": "create", "workspace": str(ws)},
        )
    )
    heartbeat(r, job)
    time.sleep(0.05)

    engineers = [
        e
        for e in (job.get("org_snapshot") or {}).get("employees") or []
        if "engineer" in (e.get("title") or "").lower() or e.get("adapter_pref") == "openhands"
    ]
    events.append(
        publish(
            r,
            run_id,
            "agent.message",
            {
                "message": f"Mapped {len(engineers)} engineer(s); workspace={ws}",
                "engineers": [e.get("codename") for e in engineers],
            },
        )
    )

    artifact_uri = f"file://{sample}"
    approvals = [
        {
            "action_tag": "deploy",
            "title": "Needs you: approve simulated deploy",
            "waiting_on": "founder",
            "suggested_actions": [
                {"id": "approve_deploy", "label": "Approve deploy", "decision": "approved"},
                {"id": "reject_deploy", "label": "Block deploy", "decision": "rejected"},
            ],
            "payload": {
                "workspace": str(ws),
                "file": str(sample),
                "requires_docker_for_real": True,
                "isolation": "per_run_id",
            },
        }
    ]
    events.append(publish(r, run_id, "approval.needed", approvals[0]))
    events.append(publish(r, run_id, "artifact.produced", {"uri": artifact_uri, "kind": "file"}))
    events.append(
        publish(r, run_id, "run.finished", {"outcome": "succeeded", "dispatch_id": dispatch_id})
    )

    result = _terminal(
        job,
        "succeeded",
        f"OpenHands stub edited {sample.name} in isolated workspace {ws}; deploy gated. Docker blocked.",
        events,
        approvals,
        artifacts=[{"kind": "file", "uri": artifact_uri, "meta": {"workspace": str(ws), "run_id": run_id}}],
    )
    # Do not destroy by default so smoke can verify file; contract still enforces isolation
    if os.getenv("OPENHANDS_DESTROY_ON_FINISH", "0") == "1":
        destroy_workspace(ws)
    return result


def _terminal(
    job: dict[str, Any],
    status: str,
    summary: str,
    events: list,
    approvals: list,
    artifacts: list | None = None,
) -> dict[str, Any]:
    return {
        "run_id": job["run_id"],
        "dispatch_id": job.get("dispatch_id"),
        "adapter_protocol_version": 1.1,
        "heartbeat_at": datetime.now(UTC).isoformat(),
        "status": status,
        "outcome": status,
        "summary": summary,
        "error": None if status == "succeeded" else summary,
        "usage": {"prompt_tokens": 40, "completion_tokens": 20, "cost_usd": 0.03},
        "upstream": {
            "framework": "openhands",
            "mode": "stub",
            "docker_available": docker_available(),
            "workspace_isolation": "per_run_id",
        },
        "artifacts": artifacts or [],
        "approvals_needed": approvals,
        "events": [{"type": e["type"], "payload": e.get("payload")} for e in events],
    }


def handle_job(job: dict[str, Any], r: redis.Redis) -> dict[str, Any]:
    if (job.get("adapter") or "") != "openhands":
        return {
            "run_id": job.get("run_id"),
            "dispatch_id": job.get("dispatch_id"),
            "status": "failed",
            "outcome": "failed",
            "error": "Wrong adapter",
            "usage": {},
            "upstream": {},
            "artifacts": [],
            "events": [],
        }
    try:
        if STUB or not docker_available():
            return handle_stub(job, r)
        return {
            "run_id": job["run_id"],
            "dispatch_id": job.get("dispatch_id"),
            "status": "failed",
            "outcome": "failed",
            "error": "Docker present but Agent Server not configured",
            "usage": {},
            "upstream": {"framework": "openhands", "mode": "unconfigured"},
            "artifacts": [],
            "events": [],
        }
    except Exception as exc:
        return {
            "run_id": job["run_id"],
            "dispatch_id": job.get("dispatch_id"),
            "status": "failed",
            "outcome": "failed",
            "error": str(exc),
            "usage": {},
            "upstream": {"traceback": traceback.format_exc()[-500:]},
            "artifacts": [],
            "events": [{"type": "run.finished", "payload": {"outcome": "failed", "error": str(exc)}}],
        }


def main() -> None:
    r = client()
    WORKSPACE_ROOT.mkdir(parents=True, exist_ok=True)
    print(f"[openhands-adapter] protocol=1.1 stub={STUB} root={WORKSPACE_ROOT}")
    while True:
        item = r.blpop(JOB_QUEUE, timeout=5)
        if not item:
            continue
        _, raw = item
        try:
            job = json.loads(raw)
        except Exception:
            continue
        print(f"[openhands-adapter] run_id={job.get('run_id')} dispatch={job.get('dispatch_id')}")
        result = handle_job(job, r)
        r.rpush(RESULT_QUEUE, json.dumps(result))
        print(f"[openhands-adapter] terminal outcome={result.get('outcome')}")


if __name__ == "__main__":
    main()
