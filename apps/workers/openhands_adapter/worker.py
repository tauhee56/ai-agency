#!/usr/bin/env python3
"""OpenHands adapter worker — Adapter Protocol v1.

Preferred path: Agent Server HTTP/WS (software-agent-sdk). On this VM Docker is
unavailable, so default mode is OPENHANDS_STUB=1 which simulates a sandboxed
edit + deploy approval gate without embedding OpenHands Canvas.
"""

from __future__ import annotations

import json
import os
import shutil
import time
import traceback
from pathlib import Path
from typing import Any

import redis

JOB_QUEUE = os.getenv("OPENHANDS_JOB_QUEUE", "aicos:jobs:openhands")
# Also listen on shared queue for adapter=openhands if OPENHANDS_SHARED_QUEUE=1
SHARED_QUEUE = os.getenv("JOB_QUEUE", "aicos:jobs")
RESULT_QUEUE = os.getenv("RESULT_QUEUE", "aicos:results")
EVENTS_PREFIX = os.getenv("EVENTS_CHANNEL_PREFIX", "aicos:run:")
REDIS_URL = os.getenv("REDIS_URL", "redis://localhost:6379/0")
STUB = os.getenv("OPENHANDS_STUB", "1") == "1"
WORKSPACE_ROOT = Path(os.getenv("OPENHANDS_WORKSPACE_ROOT", "/tmp/aicos-openhands"))


def client() -> redis.Redis:
    return redis.from_url(REDIS_URL, decode_responses=True)


def docker_available() -> bool:
    return shutil.which("docker") is not None


def publish(r: redis.Redis, run_id: str, event_type: str, payload: dict[str, Any] | None = None) -> dict:
    ev = {"type": event_type, "payload": payload or {}, "run_id": run_id}
    r.publish(f"{EVENTS_PREFIX}{run_id}", json.dumps(ev))
    return ev


def cancelled(r: redis.Redis, run_id: str) -> bool:
    return r.get(f"aicos:run:cancel:{run_id}") == "1"


def handle_stub(job: dict[str, Any], r: redis.Redis) -> dict[str, Any]:
    run_id = job["run_id"]
    events = []
    events.append(publish(r, run_id, "run.started", {"adapter": "openhands", "mode": "stub", "docker": False}))

    if cancelled(r, run_id):
        return {
            "run_id": run_id,
            "status": "cancelled",
            "summary": "Cancelled before sandbox start",
            "error": None,
            "usage": {"cost_usd": 0},
            "upstream": {"framework": "openhands", "mode": "stub"},
            "artifacts": [],
            "events": events,
        }

    ws = WORKSPACE_ROOT / run_id
    ws.mkdir(parents=True, exist_ok=True)
    sample = ws / "hello.py"
    sample.write_text("# generated by openhands stub\nprint('hello from sandbox stub')\n")
    events.append(
        publish(
            r,
            run_id,
            "tool.result",
            {"tool": "FileEditorTool", "path": str(sample), "action": "create"},
        )
    )
    time.sleep(0.05)

    # Map Engineer employees
    engineers = [
        e
        for e in (job.get("org_snapshot") or {}).get("employees") or []
        if "engineer" in (e.get("title") or "").lower() or e.get("adapter_pref") == "openhands"
    ]
    events.append(
        publish(
            r,
            run_id,
            "agent.message",
            {
                "message": f"Mapped {len(engineers)} engineer employee(s) to coding conversation stub",
                "engineers": [e.get("codename") for e in engineers],
            },
        )
    )

    artifact_uri = f"file://{sample}"
    approvals = [
        {
            "action_tag": "deploy",
            "title": "Approve simulated deploy from OpenHands sandbox stub",
            "payload": {"workspace": str(ws), "file": str(sample), "requires_docker_for_real": True},
        }
    ]
    events.append(publish(r, run_id, "approval.needed", approvals[0]))
    events.append(publish(r, run_id, "artifact.produced", {"uri": artifact_uri, "kind": "file"}))

    if cancelled(r, run_id):
        return {
            "run_id": run_id,
            "status": "cancelled",
            "summary": "Cancelled after edit, before finish",
            "usage": {"cost_usd": 0.01},
            "upstream": {"framework": "openhands", "mode": "stub"},
            "artifacts": [{"kind": "file", "uri": artifact_uri}],
            "approvals_needed": approvals,
            "events": [{"type": e["type"], "payload": e.get("payload")} for e in events],
        }

    return {
        "run_id": run_id,
        "status": "succeeded",
        "summary": f"OpenHands stub edited {sample.name} in workspace; deploy gated on Founder approval. Docker not available on host.",
        "error": None,
        "usage": {"prompt_tokens": 40, "completion_tokens": 20, "cost_usd": 0.03},
        "upstream": {
            "framework": "openhands",
            "mode": "stub",
            "docker_available": False,
            "agent_server": None,
        },
        "artifacts": [{"kind": "file", "uri": artifact_uri, "meta": {"workspace": str(ws)}}],
        "approvals_needed": approvals,
        "events": [{"type": e["type"], "payload": e.get("payload")} for e in events],
    }


def handle_job(job: dict[str, Any], r: redis.Redis) -> dict[str, Any]:
    if (job.get("adapter") or "") != "openhands":
        # Not ours — should not happen on dedicated queue
        return {
            "run_id": job.get("run_id"),
            "status": "failed",
            "error": "Wrong adapter for openhands worker",
            "usage": {},
            "upstream": {},
            "artifacts": [],
            "events": [],
        }
    try:
        if STUB or not docker_available():
            return handle_stub(job, r)
        # Real Agent Server path reserved
        return {
            "run_id": job["run_id"],
            "status": "failed",
            "error": "Docker present but Agent Server integration not configured (OPENHANDS_AGENT_SERVER_URL unset)",
            "usage": {},
            "upstream": {"framework": "openhands", "mode": "unconfigured"},
            "artifacts": [],
            "events": [],
        }
    except Exception as exc:
        return {
            "run_id": job["run_id"],
            "status": "failed",
            "error": str(exc),
            "usage": {},
            "upstream": {"traceback": traceback.format_exc()[-500:]},
            "artifacts": [],
            "events": [],
        }


def main() -> None:
    r = client()
    print(
        f"[openhands-adapter] stub={STUB} docker={docker_available()} "
        f"listening shared={SHARED_QUEUE} dedicated={JOB_QUEUE}"
    )
    while True:
        item = r.blpop(JOB_QUEUE, timeout=5)
        if not item:
            continue
        _, raw = item
        try:
            job = json.loads(raw)
        except Exception:
            continue
        print(f"[openhands-adapter] run_id={job.get('run_id')}")
        result = handle_job(job, r)
        r.rpush(RESULT_QUEUE, json.dumps(result))
        print(f"[openhands-adapter] status={result.get('status')}")


if __name__ == "__main__":
    main()
